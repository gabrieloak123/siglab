-- 1. Tabela de Usuários (users)
CREATE TABLE IF NOT EXISTS users (
    id BIGSERIAL PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    interest_areas TEXT[],
    groups BIGINT[]
);

-- 2. Tabela de Grupos de Pesquisa (research_group)
CREATE TABLE IF NOT EXISTS research_group (
    group_id VARCHAR(255) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    research_fields TEXT[]
);

-- 3. Tabela de Junção (user_research_group)
CREATE TABLE IF NOT EXISTS user_research_group (
    user_email VARCHAR(255) NOT NULL,
    group_id VARCHAR(255) NOT NULL,
    is_leader BOOLEAN NOT NULL,
    PRIMARY KEY (user_email, group_id),
    CONSTRAINT fk_user_research_group_user
        FOREIGN KEY (user_email) REFERENCES users (email) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_user_research_group_group
        FOREIGN KEY (group_id) REFERENCES research_group (group_id) ON DELETE CASCADE ON UPDATE CASCADE
);

-- 4. Tabela de colunas do quadro Kanban
  CREATE TABLE kanban_columns (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(255) NOT NULL,
      column_order INTEGER NOT NULL,
      research_group_id VARCHAR(255) NOT NULL,

      CONSTRAINT fk_kanban_column_research_group
          FOREIGN KEY (research_group_id)
          REFERENCES research_group (group_id)
          ON DELETE CASCADE,

      CONSTRAINT uk_kanban_column_group_order
          UNIQUE (research_group_id, column_order),

      CONSTRAINT uk_kanban_column_id_group
          UNIQUE (id, research_group_id)
  );

-- 5. Tabela de tareafs do quadro Kanban
  CREATE TABLE kanban_tasks (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      group_id VARCHAR(255) NOT NULL,
      created_by_id BIGINT NOT NULL,
      assigned_to_id BIGINT,
      title VARCHAR(255) NOT NULL,
      description TEXT,
      tags VARCHAR(255)[],
      column_id BIGINT NOT NULL,

      CONSTRAINT fk_kanban_task_research_group
          FOREIGN KEY (group_id)
          REFERENCES research_group (group_id)
          ON DELETE CASCADE,

      CONSTRAINT fk_kanban_task_creator
          FOREIGN KEY (created_by_id)
          REFERENCES users (id),

      CONSTRAINT fk_kanban_task_assignee
          FOREIGN KEY (assigned_to_id)
          REFERENCES users (id)
          ON DELETE SET NULL,

      CONSTRAINT fk_kanban_task_column
          FOREIGN KEY (column_id, group_id)
          REFERENCES kanban_columns (id, research_group_id)
          ON DELETE CASCADE
  );

  CREATE INDEX idx_kanban_columns_group
      ON kanban_columns (research_group_id);

  CREATE INDEX idx_kanban_tasks_group
      ON kanban_tasks (group_id);

  CREATE INDEX idx_kanban_tasks_column
      ON kanban_tasks (column_id);

  CREATE INDEX idx_kanban_tasks_assignee
      ON kanban_tasks (assigned_to_id);

-- 6. Posts do grupo
CREATE TABLE IF NOT EXISTS posts (
    id BIGSERIAL PRIMARY KEY,
    group_id VARCHAR(255),
    publisher_user_id BIGINT,
    title VARCHAR(255),
    description TEXT,
    tags TEXT[],
    file_path VARCHAR(500),
    CONSTRAINT fk_posts_publisher
        FOREIGN KEY (publisher_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_posts_research_group
        FOREIGN KEY (group_id) REFERENCES research_group (group_id) ON DELETE CASCADE ON UPDATE CASCADE
);
